"""Week 2: score baseline B0 (carry forward) with the grader — the number every tracker must beat.

For each episode in the split: build B0's ledger from the opening report (`eval/baselines/
carry_forward.py`), grade it against the target report at the episode's frozen level, and add up.
Only **dev** is scored this week: the test split is run once per version, in week 8 (§9.5).

Outputs: `$AI_DEBT_DATA/week2/b0_<split>.json` (every episode, for code) and docs/baseline_b0.md
(for people).

Usage:  python scripts/score_baseline.py [dev]
"""

from __future__ import annotations

import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

from ai_debt_tracker import config
from ai_debt_tracker.eval.answer_key import AnswerKey, grading_level
from ai_debt_tracker.eval.baselines.carry_forward import carry_forward, opening_report
from ai_debt_tracker.eval.grader import grade_episode, summarise
from review_universe import extracted_periods

ROOT = Path(__file__).resolve().parents[1]
SPLIT = sys.argv[1] if len(sys.argv) > 1 else "dev"


def pct(t):
    p, lo, hi = t
    return "—" if p != p else f"**{p:.1%}** ({lo:.1%}–{hi:.1%})"


def main() -> int:
    if SPLIT != "dev" and "--test-ok" not in sys.argv:
        raise SystemExit("B0 is scored on dev this week; the test split is run once per version (DESIGN.md §9.5)")
    with open(ROOT / "manifests" / f"{SPLIT}.csv", encoding="utf-8") as f:
        eps = list(csv.DictReader(line for line in f if not line.startswith("#")))
    ak = AnswerKey(extracted_periods(), {int(e["cik"]) for e in eps})
    records, results, rows = {}, [], []
    for e in eps:
        cik = int(e["cik"])
        reports = ak.reports(cik)
        for r in reports:
            if r["adsh"] not in records:
                records[r["adsh"]] = ak.filing_record(r["adsh"])
        target, start = records[e["target_adsh"]], records[e["start_adsh"]]
        opening, note = opening_report(reports, e["start_adsh"], e["graded_level"], records)
        ledger = carry_forward(opening, e["target_period"])
        start_for_changes = start if grading_level(start)["level"] == "L1" else None
        g = grade_episode(target, ledger, e["graded_level"], start_for_changes)
        g.update({"episode": e["episode_id"], "company": e["company"], "group": e["group"], "opening": note})
        results.append(g)
        rows.append(e)
    out_dir = config.data_dir() / "week2"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"b0_{SPLIT}.json").write_text(json.dumps(results, indent=1, default=str))
    s = summarise(results)
    by_group = defaultdict(list)
    for r in results:
        by_group[r["group"]].append(r)
    write_doc(s, results, {g: summarise(rs) for g, rs in by_group.items()})
    print(json.dumps({k: v for k, v in s.items() if k != "l3"}, indent=1, default=str))
    return 0


def write_doc(s, results, groups):
    l1, l2 = s.get("l1", {}), s.get("l2", {})
    ch = l1.get("changes", {})
    walked = sum(r["opening"].startswith("walked back") for r in results)
    L = [f"# Baseline B0 — carry forward, scored on {SPLIT}\n",
         "> Generated by `scripts/score_baseline.py` with the grader in `src/ai_debt_tracker/eval/grader.py`. "
         f"Every episode: `$AI_DEBT_DATA/week2/b0_{SPLIT}.json`. Intervals are 95% bootstrap over episodes.\n",
         "## What B0 does\n",
         "Reads nothing. It takes the last report itemised finely enough for the episode's level, drops bonds "
         "whose maturity year is before the target quarter's year, and calls that the answer "
         f"(`eval/baselines/carry_forward.py`). In {walked} of {len(results)} episodes the start report was too "
         "coarse and B0 walked back to an earlier, itemised one.\n",
         "## Results\n",
         f"**L1 — per bond** ({l1.get('episodes', 0)} episodes, {l1.get('truth', 0)} true bonds):\n",
         f"- Bond recall: {pct(l1['recall'])}" if l1 else "- (no L1 episodes)",
         f"- Bond precision: {pct(l1['precision'])}" if l1 else "",
         f"- Principal accuracy on matched bonds: {pct(l1['principal_accuracy'])}" if l1 else "",
         f"- Episodes reproduced exactly (every bond, nothing extra): **{l1.get('exact_episodes', 0)} of {l1.get('episodes', 0)}**",
         ""]
    if ch:
        L += [f"**Change detection** ({ch['episodes']} episodes whose start report is itemised too; "
              f"{ch['episodes_with_change']} of them have at least one bond added or removed):\n",
              f"- New bonds caught: {pct(ch['added_recall'])} of {ch['added']}",
              f"- Removed bonds caught: {pct(ch['removed_recall'])} of {ch['removed']}\n",
              "B0 cannot catch a new bond by construction; it catches a removal only when the bond's maturity "
              "year has passed. **This is the headroom:** every new bond, and every early repayment, is "
              "something only reading the filings can find.\n"]
    if l2:
        L += [f"**L2 — per offering** ({l2['episodes']} episodes, {l2['truth']} true units): recall {pct(l2['recall'])}, "
              f"precision {pct(l2['precision'])}.\n"]
    L += ["**L3 — totals** (every episode, wherever the target report tags the figure):\n",
          "| Figure | Graded | Within 2% | B0 had no figure | Median abs. error where it had one |", "|---|---|---|---|---|"]
    names = {"total_debt": "Total debt", "current": "Current portion", "due_next_12m": "Due in 12 months",
             "due_2_5": "Due in years 2-5", "due_after_5": "Due after year 5"}
    for k in names:
        v = s["l3"].get(k)
        if v:
            err = f"{v['median_abs_error_pct']:.1f}%" if v["median_abs_error_pct"] is not None else "—"
            L.append(f"| {names[k]} | {v['graded']} | {v['within_2pct']} | {v['not_provided']} | {err} |")
    L.append("\nMost reports tag the maturity ladder only in the annual report, so a carried-forward 10-Q has no "
             "ladder to offer a 10-K target: those count under *B0 had no figure*.\n")
    L += ["\n## By company group (L1)\n", "| Group | Episodes | Bond recall | Bond precision | Exact |", "|---|---|---|---|---|"]
    for g, gs in sorted(groups.items()):
        if "l1" in gs:
            L.append(f"| {g} | {gs['l1']['episodes']} | {gs['l1']['recall'][0]:.1%} | {gs['l1']['precision'][0]:.1%} | "
                     f"{gs['l1']['exact_episodes']} |")
    misses = sorted(((r["company"], r["episode"], len(r["l1"]["missed"]), r["l1"]["extra"]) for r in results
                     if "l1" in r and (r["l1"]["missed"] or r["l1"]["extra"])), key=lambda x: -(x[2] + x[3]))
    L += ["\n## Where B0 is wrong most (L1)\n", "| Company | Episode | Bonds missed | Extra bonds |", "|---|---|---|---|"]
    L += [f"| {c} | {ep} | {m} | {x} |" for c, ep, m, x in misses[:10]]
    (ROOT / "docs" / f"baseline_b0.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
