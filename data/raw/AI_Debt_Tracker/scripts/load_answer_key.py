"""Week 1: load the answer key for 10 companies from the SEC notes data (DESIGN.md §11, week 1).

Writes one JSON record per 10-Q/10-K (instruments with coupon, maturity, face, carrying, class;
company totals; the report's grading level and coverage) to `$AI_DEBT_DATA/answer_key/<cik>/`,
and a human-readable summary to docs/answer_key_week1.md (P5: the log is for agents, the report
is for people).

The ten were chosen to cover every grading situation the universe review found, not the easy
ones: a quiet issuance-grouped hyperscaler (Microsoft, L2), offering-level (Alphabet), per-bond
only in annual reports (Oracle, Intel — P19), per-bond with parallel offering members
(Broadcom), number words in member names (Equinix — P20), delayed-draw facilities (CoreWeave —
P6), a fast-growing neocloud (Cipher Mining), a clean chip issuer (Nvidia) and totals only
(Vistra).

Week 2 hand-checks 10 company-quarters of this against the debt tables in the reports; the
summary below ends with the checklist for that.

Usage:  python scripts/load_answer_key.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from ai_debt_tracker import config
from ai_debt_tracker.eval.answer_key import AnswerKey, grading_level
from review_universe import DEV, TEST, extracted_periods, nearest_quarter_end

ROOT = Path(__file__).resolve().parents[1]
TEN = {789019: "Microsoft", 1652044: "Alphabet", 1341439: "Oracle", 1045810: "Nvidia", 50863: "Intel",
       1730168: "Broadcom", 1101239: "Equinix", 1769628: "CoreWeave", 1819989: "Cipher Mining", 1692819: "Vistra"}


def bn(x):
    return f"{x / 1e9:,.1f}" if x else "—"


def main() -> int:
    ak = AnswerKey(extracted_periods(), set(TEN))
    out_root = config.data_dir() / "answer_key"
    L = ["# Answer key — Week 1 load (10 companies)\n",
         "> Generated by `scripts/load_answer_key.py` from the SEC Financial Statement and Notes data. Full records "
         "(every instrument, every total) are in `$AI_DEBT_DATA/answer_key/<cik>/<accession>.json` (local, not in git). "
         "Grader side only — the agent never sees these (P11).\n",
         "## Per report\n",
         "Level and coverage use the answer-key rule (`eval/answer_key.grading_level`): the share of total debt that "
         "itemised instruments account for. *Bonds keyed* = outstanding bonds with currency, coupon and maturity year.\n",
         "| Company | Report | Quarter | Split | Level | Coverage itemised / offerings | Total debt $bn (basis) | Outstanding members | Bonds keyed |",
         "|---|---|---|---|---|---|---|---|---|"]
    n_files = n_inst = 0
    latest = {}
    for cik, name in TEN.items():
        for r in ak.reports(cik):
            rec = ak.filing_record(r["adsh"])
            g = grading_level(rec)
            rec["grading"] = g
            q = nearest_quarter_end(r["period"])
            split = "dev" if DEV[0] <= q <= DEV[1] else "test" if TEST[0] <= q <= TEST[1] else "—"
            d = out_root / str(cik)
            d.mkdir(parents=True, exist_ok=True)
            (d / f"{r['adsh']}.json").write_text(json.dumps(rec, indent=1, default=str))
            n_files += 1
            n_inst += len(rec["instruments"])
            outs = sum(v for k, v in g["counts"].items() if k != "bond_keyed")
            basis = "tagged sum" if g["total_basis"].startswith("sum of tagged") else g["total_basis"]
            L.append(f"| {name} | {r['form']} {r['period']} | {q} | {split} | {g['level']} | "
                     f"{g['coverage_itemised']:.0%} / {g['coverage_offerings']:.0%} | {bn(g['total_debt'])} ({basis}) | "
                     f"{outs} | {g['counts'].get('bond_keyed', 0)} |")
            latest[cik] = (r, rec)
        print(f"{name:14s} {len(ak.reports(cik))} reports", flush=True)

    L.append("\n## Latest report, instrument by instrument (outstanding only, first 12)\n")
    for cik, (r, rec) in latest.items():
        outs = [i for i in rec["instruments"] if i["outstanding"]]
        L.append(f"**{TEN[cik]}** — {r['form']} {r['period']}, {len(outs)} outstanding members, level {rec['grading']['level']}\n")
        L.append("| Member | Class | Coupon % | Maturity | Currency | Face | Carrying (USD) | Coupon from |")
        L.append("|---|---|---|---|---|---|---|---|")
        for i in outs[:12]:
            L.append(f"| `{i['member'][:48]}` | {i['klass']} | {i['rate'] if i['rate'] is not None else '—'} | "
                     f"{i['maturity_year'] or '—'} | {i['currency'] or '—'} | {f'{i['face']:,.0f}' if i['face'] else '—'} | "
                     f"{f'{i['carrying']:,.0f}' if i['carrying'] else '—'} | {i['rate_from'] or '—'} |")
        L.append("")
    L.append("## Week 2 hand-check (10 company-quarters)\n")
    L.append("For each company, open the latest report's debt note and tick: every bond in the table is in the list "
             "above (or explained as untagged); coupons and maturities agree; total debt agrees with the balance sheet. "
             "Record disagreements in `docs/worklog.md` — the grader has to agree 10/10 before Week 3 (§11).\n")
    for cik, (r, _) in latest.items():
        L.append(f"- [ ] {TEN[cik]} — {r['form']} {r['period']} (`{r['adsh']}`)")
    (ROOT / "docs" / "answer_key_week1.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"\n{n_files} filing records, {n_inst} instrument records -> {out_root}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
